export const UI: Record<Lang, Record<Key, string>> = { en, nl };
export type UiKey = Key;

/** Look up interface text, filling `{name}` placeholders. */
export function translate(lang: Lang, key: UiKey, vars?: Record<string, string | number>): string {
  let text = UI[lang][key] ?? UI.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}
